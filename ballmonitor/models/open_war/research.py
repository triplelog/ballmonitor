"""Sets Open WAR's replacement levels and writes RESEARCH.md (generated; never hand-edit).

    python -m ballmonitor.models.open_war.research

WAR is linear in the two replacement levels, so each is solved directly: over the 2000-2024
seasons, batting WAR per 30 teams should average TARGET_BAT and pitching TARGET_PITCH (the 1,000-win,
57/43 replacement level Baseball-Reference and FanGraphs adopted in 2013). Then reports league totals
by era and the career and single-season leaders as a sanity check.
"""

from __future__ import annotations

import csv
import datetime as dt
from collections import Counter, defaultdict
from pathlib import Path

from ballmonitor.core import registry

from . import engine as E

DIR = Path(__file__).resolve().parent
TARGET_BAT, TARGET_PITCH = 570.0, 430.0
YEARS = range(2000, 2025)


def per30(seasons, teams):
    by = defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])   # bWAR, pWAR, PA/600/rpw, IP/9/rpw
    for r in seasons:
        b = by[r["yearID"]]
        b[0] += r["bWAR"]
        b[1] += r["pWAR"]
        if r["bat_rep"]:
            b[2] += r["PA"] / 600 / r["rpw"]
        b[3] += r["IP"] / 9 / r["rpw"]
    return {y: [v * 30 / teams[y] for v in vals] for y, vals in by.items() if teams.get(y)}


def main() -> None:
    m = registry.load_model("open_war")
    p = m.params
    teams = Counter(int(t["yearID"]) for t in csv.DictReader((E.LAHMAN / "Teams.csv").open(encoding="utf-8-sig")))
    s = E.compute(p)
    tot = per30(s, teams)
    n = len(YEARS)
    bat, pit = sum(tot[y][0] for y in YEARS) / n, sum(tot[y][1] for y in YEARS) / n
    dbat, dpit = sum(tot[y][2] for y in YEARS) / n, sum(tot[y][3] for y in YEARS) / n
    new_bat = p.batting_replacement_runs + (TARGET_BAT - bat) / dbat
    new_pit = p.pitching_replacement_runs_per_9 + (TARGET_PITCH - pit) / dpit
    m2 = registry.load_model("open_war", None, {"batting_replacement_runs": round(new_bat, 2),
                                                "pitching_replacement_runs_per_9": round(new_pit, 3)})
    s2 = E.compute(m2.params)
    tot2 = per30(s2, teams)
    names = {r["playerID"]: f"{r['nameFirst']} {r['nameLast']}" for r in csv.DictReader((E.LAHMAN / "People.csv").open(encoding="utf-8-sig"))}
    career = Counter()
    for r in s2:
        career[r["playerID"]] += r["WAR"]
    lines = ["# Open WAR: research", "",
             f"Generated by `python -m ballmonitor.models.open_war.research` on {dt.date.today()}. Do not edit by hand.", "",
             "## Replacement levels", "",
             f"Over {YEARS.start}-{YEARS.stop - 1}, per 30 teams, the old levels gave {bat:.0f} batting and {pit:.0f} pitching WAR. "
             f"Solving for {TARGET_BAT:.0f} / {TARGET_PITCH:.0f} (the 2013 Baseball-Reference/FanGraphs unified replacement level):", "",
             f"- batting_replacement_runs = **{new_bat:.2f}** runs per 600 PA",
             f"- pitching_replacement_runs_per_9 = **{new_pit:.3f}** runs per 9 IP", "",
             "League WAR per 30 teams with these levels:", "", "| season | batting | pitching | total |", "|---|---|---|---|"]
    for y in (1880, 1900, 1920, 1940, 1960, 1980, 2000, 2010, 2019, 2024):
        if y in tot2:
            b, q = tot2[y][0], tot2[y][1]
            lines.append(f"| {y} | {b:.0f} | {q:.0f} | {b + q:.0f} |")
    lines += ["", "Early seasons hold less: fewer games per team and the same per-PA / per-inning levels.", "",
              "## Career leaders (sanity check)", "", "| player | Open WAR |", "|---|---|"]
    lines += [f"| {names.get(k, k)} | {v:.1f} |" for k, v in career.most_common(30)]
    lines += ["", "## Best seasons", "", "| player | year | Open WAR |", "|---|---|---|"]
    lines += [f"| {names.get(r['playerID'])} | {r['yearID']} | {r['WAR']:.1f} |" for r in sorted(s2, key=lambda r: -r["WAR"])[:15]]
    lines += ["", "Best since 1950:", "", "| player | year | Open WAR |", "|---|---|---|"]
    lines += [f"| {names.get(r['playerID'])} | {r['yearID']} | {r['WAR']:.1f} |"
              for r in sorted((r for r in s2 if r["yearID"] >= 1950), key=lambda r: -r["WAR"])[:15]]
    (DIR / "RESEARCH.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[:16]))


if __name__ == "__main__":
    main()
