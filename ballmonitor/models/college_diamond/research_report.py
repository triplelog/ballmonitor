"""Coverage checks and the RESEARCH.md writer for college_diamond (see research.py)."""

from __future__ import annotations

import json
import statistics
from pathlib import Path

from ballmonitor.models.college_diamond.data import DATA_DIR, load_games, load_teams
from ballmonitor.models.college_diamond.rpi import RpiWeights, ranks, rpi

RPI_W = {"baseball": RpiWeights(), "softball": RpiWeights(home_win=1, road_win=1, home_loss=1, road_loss=1)}


def coverage_part() -> dict:
    from ballmonitor.models.college_diamond import fetch as F
    cov = json.loads((DATA_DIR / "coverage.json").read_text())
    raw = DATA_DIR / "raw"
    out = {"seasons": {}, "rpi_vs_warren_nolan": {}}
    for key, v in cov.items():
        out["seasons"][key] = {k: v.get(k) for k in ("di_teams", "games", "game_types", "games_per_team_pre_ncaa",
                                                       "record_diff_vs_wn", "selection", "source",
                                                       "membership_anchor", "membership_inferred_changes")}
    for sport, seasons in F.WN_SEASONS.items():
        for y in seasons:
            wn = F.warren_nolan(raw, sport, y, True)
            if not wn or y not in load_teams(sport):
                continue
            G = [g for g in load_games(sport) if g.season == y]
            res = [(g.home, g.away, 1.0 if g.margin > 0 else 0.0 if g.margin < 0 else 0.5, g.neutral) for g in G]
            T = load_teams(sport)[y]
            rec: dict = {}
            for g in G:
                if g.margin:
                    a, b = (g.home, g.away) if g.margin > 0 else (g.away, g.home)
                    rec.setdefault(a, [0, 0])[0] += 1
                    rec.setdefault(b, [0, 0])[1] += 1
            m = F._match_names([(w["wn_slug"], F.name_tokens(w["name"]) | F.name_tokens(w["wn_slug"].replace("-", " ")),
                                 w["record"][:2]) for w in wn],
                               {i: (F.name_tokens(T[i]["name"]) | F.name_tokens(i.replace("-", " ")),
                                    tuple(rec.get(i, (0, 0)))) for i in T}, F.WN_ALIASES)
            row = {}
            for label, W in (("site_weighted", RpiWeights()),
                             ("unweighted", RpiWeights(home_win=1, road_win=1, home_loss=1, road_loss=1))):
                rk = ranks(rpi(res, W))
                pairs = [(w["rpi_rank"], rk[m[w["wn_slug"]]]) for w in wn if m.get(w["wn_slug"]) in rk]
                top = [(a, b) for a, b in pairs if a <= 64]
                row[label] = {"teams": len(pairs), "median_abs_rank_diff": statistics.median(abs(a - b) for a, b in pairs),
                              "top64_mean_abs_rank_diff": round(sum(abs(a - b) for a, b in top) / len(top), 2),
                              "top64_exact": sum(a == b for a, b in top)}
            out["rpi_vs_warren_nolan"][f"{sport} {y}"] = row
    return out


def _f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def write_report(path: Path, parts: dict) -> None:
    L = ["# college_diamond — research", "",
         "Generated by `python -m ballmonitor.models.college_diamond.research`; do not edit by hand.",
         "Development seasons (used for every tuning choice): baseball 2015-2019, softball 2017-2019.",
         "Test seasons (scored once with frozen settings): 2021-2026. 2020 was cancelled.", ""]
    cov = parts.get("coverage")
    if cov:
        L += ["## 1. Data coverage", "",
              "Games are D-I vs D-I only. Baseball: boydsworld.com (all seasons, with neutral sites) keyed to",
              "NCAA.com team ids; softball: NCAA.com scoreboard (2015-2022, 2026) and Warren Nolan team",
              "schedules (2023-2025). 'WN exact' = teams whose built W-L equals Warren Nolan's final record.", "",
              "| sport season | D-I teams | games | R / C / N | games per team (p10 / median) | WN exact / within 2 |",
              "|---|---|---|---|---|---|"]
        for k, v in cov["seasons"].items():
            gt = v.get("game_types") or {}
            gp = v.get("games_per_team_pre_ncaa") or {}
            wn = v.get("record_diff_vs_wn")
            L.append(f"| {k} | {v.get('di_teams')} | {v.get('games')} | {gt.get('R', 0)} / {gt.get('C', 0)} / "
                     f"{gt.get('N', 0)} | {gp.get('p10')} / {gp.get('median')} | "
                     + (f"{wn['exact']}/{wn['n']} / {wn['within_2']}/{wn['n']}" if wn else "-") + " |")
        L += ["", "RPI check (our rpi.py vs Warren Nolan's final RPI ranks; mean |rank difference| among WN's top 64):", "",
              "| sport season | site-weighted | unweighted |", "|---|---|---|"]
        for k, v in cov["rpi_vs_warren_nolan"].items():
            L.append(f"| {k} | {v['site_weighted']['top64_mean_abs_rank_diff']} "
                     f"({v['site_weighted']['top64_exact']} exact) | {v['unweighted']['top64_mean_abs_rank_diff']} "
                     f"({v['unweighted']['top64_exact']} exact) |")
        L += ["", "Baseball matches the site-weighted RPI (road win 1.3 / home win 0.7); softball matches the",
              "unweighted RPI, so the model uses those. Softball 2015-2016 coverage is poor (NCAA.com lacks",
              "most scores) and those seasons are only used as rating priors.", ""]
    st = parts.get("strength")
    if st:
        L += ["## 2. Team strength", "",
              "Walk-forward: ratings fitted on games before each Monday predict the next 7 days (March to",
              "the end of the World Series). Log loss / Brier on the home team winning, RMSE on run margin.", ""]
        for sport, v in st["sports"].items():
            L += [f"### {sport}", "", "| configuration | dev log loss | test log loss | test Brier | test RMSE runs |"
                  " weekend | midweek | postseason | first 4 weeks |", "|---|---|---|---|---|---|---|---|---|"]
            for name, c in v["configs"].items():
                L.append(f"| {name} | {_f(c['dev']['log_loss'], 4)} | {_f(c['test']['log_loss'], 4)} | "
                         f"{_f(c['test']['brier'], 4)} | {_f(c['test']['rmse_runs'], 3)} | "
                         f"{_f(c['test_weekend']['log_loss'], 4)} | {_f(c['test_midweek']['log_loss'], 4)} | "
                         f"{_f(c['test_postseason']['log_loss'], 4)} | {_f(c['test_early']['log_loss'], 4)} |")
            ch = v["chosen"]
            L += ["", f"Shipped ({v['chosen_name']}): margin cap {ch['margin_cap']:g}, power {ch['margin_power']:g}, "
                  f"ridge {ch['ridge']:g}, prior carry {ch['prior_carry']:g}, half-life {ch['half_life_days']:g} days, "
                  f"midweek weight {ch['midweek_weight']:g}. Separate win-probability scales fitted on dev: "
                  f"midweek {v['scale_midweek']:.3f} vs weekend {v['scale_weekend']:.3f} per rating unit ("
                  + ("midweek games are slightly MORE predictable from the same ratings)."
                     if v['scale_midweek'] > v['scale_weekend'] else "midweek games are less predictable)."), ""]
        bits = []
        for sport, v in st["sports"].items():
            ns = v["configs"]["+ margin compression / prior / recency (no midweek split)"]
            ws = v["configs"]["+ per-team midweek offset"]
            d = {k: ws[k]["log_loss"] - ns[k]["log_loss"] for k in ("dev", "test", "test_weekend", "test_midweek",
                                                                   "test_postseason")}
            bits.append(f"{sport}: split minus no-split log loss dev {d['dev']:+.4f}, test {d['test']:+.4f} "
                        f"(weekend {d['test_weekend']:+.4f}, midweek {d['test_midweek']:+.4f}, postseason "
                        f"{d['test_postseason']:+.4f})")
        L += ["**Weekend vs midweek.** A per-team midweek offset (shrunk toward beta x rating; tuned on dev)",
              "compared with the same ratings without it — " + "; ".join(bits) + ". Negative = the split helps.",
              "The split is shipped only if it gains at least 0.001 dev log loss (see 'Shipped' above);",
              "down-weighting midweek games was also in the search (`midweek_weight`). Variant",
              "`midweek_split` turns the offset model on.", ""]
    se = parts.get("selection")
    if se:
        L += ["## 3. Committee proxy (selection, hosts)", "",
              "At each Selection Monday/Sunday, from games before it. Fitted on development seasons; test",
              "seasons scored once. 'misses' = at-large picks by the rule that were not in the real field.", ""]
        for sport, v in se["sports"].items():
            t = v["totals"]
            L += [f"### {sport}", "",
                  f"- RPI-only at-large model: P = logistic({v['rpi_only_coef'][0]:.2f} - {v['rpi_only_coef'][1]:.2f} ln(RPI rank)); "
                  f"host model: logistic({v['host_rpi_only_coef'][0]:.2f} - {v['host_rpi_only_coef'][1]:.2f} ln(RPI rank)).",
                  f"- Test at-large log loss: RPI only {_f(v['test_at_large_rpi_only']['log_loss'], 4)} vs RPI + rating + win% "
                  f"{_f(v['test_at_large']['log_loss'], 4)} (n = {v['test_at_large']['n']} eligible non-AQ teams).",
                  f"- Test host log loss: RPI only {_f(v['test_host_rpi_only']['log_loss'], 4)} vs full {_f(v['test_host']['log_loss'], 4)}.",
                  f"- Test at-large misses (picking the top N): full model {t['misses']} vs pure RPI order {t['misses_rpi']} "
                  f"of {t['at_large']} at-large bids over {v['n_test_seasons']} seasons; hosts correct {t['host_hits']} "
                  f"vs {t['host_hits_rpi']} of {16 * v['n_test_seasons']}.", ""]
            L += ["| season | at-large | misses (model / RPI order) | hosts right (model / RPI) | seed-line MAE (model / RPI) |",
                  "|---|---|---|---|---|"]
            for s, r in v["seasons"].items():
                L.append(f"| {s} | {r['at_large']} | {r['misses']} / {r['misses_rpi_rule']} | {r['host_hits']} / "
                         f"{r['host_hits_rpi_rule']} | {_f(r['seed_line_mae'], 2)} / {_f(r['seed_line_mae_rpi_rule'], 2)} |")
            L.append("")
        L += ["The committee is close to 'RPI order': adding our rating or win % did not help out of",
              "sample, so the shipped selection and host scores use RPI rank only.", ""]
    bt = parts.get("backtest")
    if bt:
        L += ["## 4. Full-model backtest", "",
              "The shipped model run at April 1, May 1 and selection eve for every season; every D-I team",
              "scored. Benchmarks: `rpi_now` (RPI-only logistic on the RPI at the snapshot; stage by RPI",
              "bucket frequencies from dev seasons), `chalk` (rating-only, deterministic field), `base`",
              "(constant rates). Dev rows are in-sample for the tuned parts. Independent units = seasons",
              f"(baseball test {len(bt['seasons']['baseball']['test'])}, softball test {len(bt['seasons']['softball']['test'])}).", "",
              "| sport snapshot split | teams | bid Brier (model / rpi_now / chalk / base) | bid log loss (model / rpi_now / base) "
              "| host Brier (model / rpi_now / chalk) | stage log loss (model / rpi bucket) | wins MAE | wins in 80% | seed-line MAE |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k, m in bt["summary"].items():
            L.append(f"| {k.replace('|', ' ')} | {m['teams']} | {_f(m['bid_brier'])} / {_f(m['bid_rpi_now_brier'])} / "
                     f"{_f(m['bid_chalk_brier'])} / {_f(m['bid_base_brier'])} | {_f(m['bid_ll'])} / {_f(m['bid_rpi_now_ll'])} / "
                     f"{_f(m['bid_base_ll'])} | {_f(m['host_brier'])} / {_f(m['host_rpi_now_brier'])} / {_f(m['host_chalk_brier'])} | "
                     f"{_f(m['stage_ll'])} / {_f(m['stage_ll_rpi_bucket'])} | {_f(m['wins_abs_err'], 2)} | "
                     f"{_f(m['wins_in_80'], 2)} | {_f(m.get('seed_line_abs_err'), 2)} |")
        L += ["", "Selection-eve benchmark that knows the automatic qualifiers (`rpi_aq`: AQ = 0.999, others",
              "RPI-only logistic) — bid Brier / log loss:", ""]
        for k, m in bt["summary"].items():
            if "selection" in k and m.get("bid_rpi_aq_brier") is not None:
                L.append(f"- {k.replace('|', ' ')}: model {_f(m['bid_brier'])} / {_f(m['bid_ll'])} vs rpi_aq "
                         f"{_f(m['bid_rpi_aq_brier'])} / {_f(m['bid_rpi_aq_ll'])}")
        L += ["", "Reliability of P(bid), test seasons, all snapshots pooled:", "",
              "| sport | bin | teams | mean P | share in field |", "|---|---|---|---|---|"]
        for sport, rows in bt.get("reliability_test_bid", {}).items():
            for r in rows:
                L.append(f"| {sport} | {r['bin']} | {r['n']} | {r['mean_p']:.3f} | {r['freq']:.3f} |")
        L += ["", "Notes: `rpi_now` ignores automatic bids before selection eve, so it is weak for small-",
              "conference champions; `chalk` is 0/1 (log loss clipped at 1%). Seed-line MAE is baseball",
              "only (softball 2-4 seeds are not in the data). Wins = final D-I wins incl. postseason.", "",
              f"{bt['rows']} team-snapshot rows are in data/backtest.csv (`ballmonitor backtest college_diamond`).", ""]
    path.write_text("\n".join(L) + "\n")
