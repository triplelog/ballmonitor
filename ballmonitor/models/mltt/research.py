"""Reproducible study behind mltt's default parameters -> RESEARCH.md (generated; never hand-edit).

    python -m ballmonitor.models.mltt.research

1. Rating scale: edges fitted from results alone vs the players' MLTT ratings (rating_center,
   rating_points_per_logit).
2. Walk-forward: before each match day, fit edges on every earlier game; score each game
   (actual players) and each match (pre-match lineup guess). Tune on Seasons 2-3, test on
   Season 4 so far.
3. team_rating_sd: the spread of team error that best calibrates the match forecasts.
4. Checks of the coin-flip-rally assumption: 11-10 games, Golden Game head starts.
Also writes data/backtest.csv (one row per played match).
"""

from __future__ import annotations

import csv
import datetime as dt
import math
from pathlib import Path

from ballmonitor.core import registry

from . import engine as E

DIR = Path(__file__).resolve().parent
TUNE, TEST = (2, 3), (4,)


def model(**overrides):
    return registry.load_model("mltt", None, overrides)


def walk_forward(data: E.Data, p, seasons: tuple[int, ...], shifts: tuple[float, ...] = (0.0,)) -> dict:
    """Game and match log loss / Brier over `seasons`, refitting before each match day."""
    r = E.rules(p)
    days = sorted({m.date for m in data.matches if m.final and m.season in seasons})
    games_ll = games_n = 0.0
    out = {"match": [], "games_ll": 0.0, "games_n": 0, "days": len(days),
           "weekends": len({(m.season, m.city, m.date[:7]) for m in data.matches if m.final and m.season in seasons})}
    for day in days:
        R = E.fit_ratings(data, p, as_of=day, season=int(next(m.season for m in data.matches if m.date == day)))
        for m in (m for m in data.matches if m.date == day and m.final):
            for g in m.games:
                diff = sum(R.get(x) for x in g.a) / len(g.a) - sum(R.get(x) for x in g.b) / len(g.b)
                pg = E.game_win(round(E.logistic(diff), 6), r.game_to)
                y = g.pa > g.pb
                games_ll -= math.log(pg if y else 1 - pg)
                games_n += 1
            sa = E.team_slots(data, R, m.team_a, m.season, as_of=day)
            sb = E.team_slots(data, R, m.team_b, m.season, as_of=day)
            probs = []
            for s in shifts:
                gp, q = E.slot_game_probs(sa, sb, p, r, shift=s)
                probs.append(E.summarize(E.match_distribution(gp, q, r), r))
            out["match"].append((m, [x[0] for x in probs], [x[1] for x in probs]))
    out["games_ll"], out["games_n"] = games_ll / max(games_n, 1), int(games_n)
    return out


def match_scores(rows, weights=None) -> dict:
    ll = br = pts = 0.0
    for m, wins, xpts in rows:
        w = weights or [1 / len(wins)] * len(wins)
        pw = sum(a * b for a, b in zip(w, wins))
        xp = sum(a * b for a, b in zip(w, xpts))
        y = m.points_a > m.points_b
        ll -= math.log(min(max(pw if y else 1 - pw, 1e-9), 1))
        br += (pw - y) ** 2
        pts += abs(xp - m.points_a)
    n = max(len(rows), 1)
    return {"n": len(rows), "log_loss": ll / n, "brier": br / n, "points_mae": pts / n}


def gauss_shifts(sd: float, k: int = 7) -> tuple[list[float], list[float]]:
    """Gauss-Hermite points for N(0, sd^2) (the difference of two teams' errors has sd*sqrt2)."""
    import numpy as np  # research only
    x, w = np.polynomial.hermite.hermgauss(k)
    return [float(v) * math.sqrt(2) * sd for v in x], [float(v) / math.sqrt(math.pi) for v in w]


def main() -> None:
    m0 = model()
    data = E.load(m0.dir / "data")
    lines = ["# MLTT: research", "",
             f"Generated by `python -m ballmonitor.models.mltt.research` on {dt.date.today()} from "
             f"data fetched {data.meta.get('fetched', '?')} (last result {data.meta.get('last_result', '?')}). "
             "Do not edit by hand.", ""]
    finals = [m for m in data.matches if m.final]
    lines += [f"Data: {len(finals)} played matches ({sum(m.stage == 'playoff' for m in finals)} Final Four), "
              f"{len(data.games)} Stage One games, {len(data.players)} players, Seasons {data.seasons()[0]}-{data.seasons()[-1]} "
              "(Season 1 is not in MLTT's results API).", ""]

    # 1 ----------------------------------------------------------------- rating scale
    # Each player-season: edge fitted from that season's results alone vs the SPINDEX rating the
    # player had before the season started (dated, so no hindsight).
    pm = model(use_rating_prior=False, prior_rallies=50.0, season_decay=0.0, doubles_weight=1.0)
    pts = []
    for season in data.seasons():
        start = min(m.date for m in data.matches if m.season == season)
        R = E.fit_ratings(data, pm.params, season=season)
        for x, v in R.value.items():
            rating = data.rating_on(x, start)
            if rating is not None and R.rallies[x] >= 150:
                pts.append((rating, v, R.rallies[x]))
    sw = sum(w for _, _, w in pts)
    mx = sum(x * w for x, _, w in pts) / sw
    my = sum(y * w for _, y, w in pts) / sw
    slope = sum(w * (x - mx) * (y - my) for x, y, w in pts) / sum(w * (x - mx) ** 2 for x, _, w in pts)
    center = mx - my / slope
    corr = (sum(w * (x - mx) * (y - my) for x, y, w in pts)
            / math.sqrt(sum(w * (x - mx) ** 2 for x, _, w in pts) * sum(w * (y - my) ** 2 for _, y, w in pts)))
    per_logit = 1 / slope
    n_hist = sum(1 for x in data.players if data.rating_on(x, None) is not None)
    lines += ["## 1. What an MLTT rating point is worth", "",
              f"SPINDEX rating histories (spindex.mltt.com) cover {n_hist} of {len(data.players)} players: the rating "
              "each had before any day. For each player-season with at least 150 rallies "
              f"({len(pts)}), the edge fitted from that season's results alone, regressed on the rating the player had "
              "*before the season* (weighted by rallies): "
              f"**{per_logit:.0f} rating points per unit of rally edge**, average MLTT player at **{center:.0f}** "
              f"(correlation {corr:.2f}). No hindsight: the rating predates the results.", "",
              f"So 100 rating points is about {100 / per_logit:.3f} in edge: a {E.logistic(100 / per_logit):.1%} rally chance, "
              f"a {E.game_win(E.logistic(100 / per_logit)):.1%} chance to win a game.", ""]
    per_logit, center = round(per_logit, -1), round(center, -1)

    # 2 ----------------------------------------------------------------- walk-forward
    base = dict(rating_center=center, rating_points_per_logit=per_logit, season_decay=0.5, doubles_weight=0.5,
                team_rating_sd=0.0)
    grid = []
    for use in (False, True):
        for pr in (25.0, 50.0, 100.0, 200.0, 400.0, 800.0, 1600.0):
            grid.append(dict(base, use_rating_prior=use, rating_source="dated", prior_rallies=pr))
    lines += ["## 2. Walk-forward forecasts", "",
              "Before each match day, edges are refitted on every earlier game. *Game* scores use the players who "
              "actually played (tests the ratings); *match* scores use the pre-match lineup guess (each slot: the "
              f"players the team used there so far) — the forecast a fan would see. Tuned on Seasons {TUNE}, tested on Season {TEST[0]}.", ""]
    res = []
    for cfg in grid:
        mm = model(**cfg)
        wf = walk_forward(data, mm.params, TUNE)
        res.append((cfg, wf["games_ll"], match_scores(wf["match"])))
    coin = math.log(2)
    lines += [f"Stage 1, tuning seasons ({wf['games_n']} games, {len(wf['match'])} matches, {wf['days']} match days in "
              f"{wf['weekends']} weekends). Coin flip: log loss {coin:.4f}. Season decay 0.5, doubles weight 0.5.", "",
              "| prior | prior rallies | game log loss | match log loss | match Brier |", "|---|---|---|---|---|"]
    for cfg, gll, ms in res:
        lines.append(f"| {'dated MLTT rating' if cfg['use_rating_prior'] else 'average'} | {cfg['prior_rallies']:.0f} | "
                     f"{gll:.4f} | {ms['log_loss']:.4f} | {ms['brier']:.4f} |")
    best_no = min((x for x in res if not x[0]["use_rating_prior"]), key=lambda x: x[1])
    best_yes = min((x for x in res if x[0]["use_rating_prior"]), key=lambda x: x[1])
    best = best_yes[0]
    lines += ["", f"Best by game log loss: results only {best_no[0]['prior_rallies']:.0f} rallies ({best_no[1]:.4f}); "
              f"with the dated rating prior {best_yes[0]['prior_rallies']:.0f} rallies ({best_yes[1]:.4f}).", ""]

    (DIR / "RESEARCH.md").write_text("\n".join(lines + ["", "(partial run)"]))
    res2 = []
    for sd_ in (0.25, 0.5, 1.0):
        for dw in (0.25, 0.5, 1.0):
            cfg = dict(best, season_decay=sd_, doubles_weight=dw)
            wf = walk_forward(data, model(**cfg).params, TUNE)
            res2.append((cfg, wf["games_ll"], match_scores(wf["match"])))
    lines += ["Stage 2, at that prior: older seasons and doubles.", "",
              "| season decay | doubles weight | game log loss | match log loss |", "|---|---|---|---|"]
    for cfg, gll, ms in res2:
        lines.append(f"| {cfg['season_decay']} | {cfg['doubles_weight']} | {gll:.4f} | {ms['log_loss']:.4f} |")
    best = min(res2, key=lambda x: x[1])[0]
    lines += ["", f"Chosen: season decay {best['season_decay']}, doubles weight {best['doubles_weight']}.", ""]

    (DIR / "RESEARCH.md").write_text("\n".join(lines + ["", "(partial run)"]))
    # 3 ---------------------------------------------------------------- team_rating_sd
    rows_sd = []
    for sd in (0.0, 0.025, 0.05, 0.1, 0.15, 0.2):
        shifts, w = gauss_shifts(sd) if sd else ([0.0], [1.0])
        wf = walk_forward(data, model(**best).params, TUNE, tuple(shifts))
        rows_sd.append((sd, match_scores(wf["match"], w)))
    best_sd = min(rows_sd, key=lambda x: x[1]["log_loss"])[0]
    lines += ["## 3. How unsure the match forecasts should be", "",
              "Each match forecast averaged over a team-edge error with this spread (per team), tuning seasons:", "",
              "| team_rating_sd | match log loss | match Brier |", "|---|---|---|"]
    lines += [f"| {sd} | {ms['log_loss']:.4f} | {ms['brier']:.4f} |" for sd, ms in rows_sd]
    lines += ["", f"Chosen: {best_sd}.", ""]

    # test season ------------------------------------------------------------------
    final = dict(best, team_rating_sd=best_sd)
    shifts, w = gauss_shifts(best_sd) if best_sd else ([0.0], [1.0])
    test_rows = []
    for name, cfg in (("chosen defaults (dated rating prior)", final),
                      ("results only (no rating prior)", dict(final, use_rating_prior=False, prior_rallies=best_no[0]["prior_rallies"])),
                      ("dated rating only (prior_rallies 100000)", dict(final, prior_rallies=100000.0)),
                      ("today's rating as prior (hindsight)", dict(final, rating_source="current"))):
        wf = walk_forward(data, model(**cfg).params, TEST, tuple(shifts))
        test_rows.append((name, wf["games_ll"], match_scores(wf["match"], w), wf))
    n_test = test_rows[0][3]
    lines += [f"## 4. Test: Season {TEST[0]} so far", "",
              f"{n_test['games_n']} games, {len(n_test['match'])} matches over {n_test['weekends']} weekends "
              "(the independent periods: a weekend's matches share players and form). Coin flip: log loss "
              f"{coin:.4f}, Brier 0.25.", "",
              "| model | game log loss | match log loss | match Brier | team points MAE |", "|---|---|---|---|---|"]
    for name, gll, ms, _ in test_rows:
        lines.append(f"| {name} | {gll:.4f} | {ms['log_loss']:.4f} | {ms['brier']:.4f} | {ms['points_mae']:.2f} |")
    lines += ["", "Only the last row uses hindsight (today's ratings already include these games); it shows how much a "
              "snapshot rating flatters a backtest.", ""]

    # 5 -------------------------------------------------------------------- checks
    p = model(**final).params
    r = E.rules(p)
    R = E.fit_ratings(data, p)
    close_pred = close_act = 0.0
    for g in data.games:
        diff = sum(R.get(x) for x in g.a) / len(g.a) - sum(R.get(x) for x in g.b) / len(g.b)
        q = E.logistic(diff)
        close_pred += math.comb(20, 10) * (q * (1 - q)) ** 10
        close_act += max(g.pa, g.pb) == 11 and min(g.pa, g.pb) == 10
    n = len(data.games)
    hs: dict[int, list[int]] = {}
    for m in finals:
        lead = m.stage_one_a - m.stage_one_b
        if lead == 0:
            continue
        h = min(abs(lead), r.max_head_start)
        leader_won = (m.golden_a > m.golden_b) == (lead > 0)
        hs.setdefault(h, []).append(leader_won)
    lines += ["## 5. Is a rally a coin flip?", "",
              f"Games decided 11-10: {close_act / n:.1%} of {n} (the coin-flip-rally model with fitted edges expects "
              f"{close_pred / n:.1%}).", "",
              "Golden Game won by the Stage One leader, by head start (even teams expected):", "",
              "| head start | matches | leader won | even-teams model |", "|---|---|---|---|"]
    for h in sorted(hs):
        v = hs[h]
        lines.append(f"| {h} | {len(v)} | {sum(v) / len(v):.0%} | {E.race_win(h, 0, 0.5, r.golden_to):.0%} |")
    decided = sum(1 for m in finals if 5 <= m.stage_one_a <= 10)
    lines += ["", "Stage One has 15 games, so the lead is always odd (head starts 1, 3 or 5).", "",
              f"The Golden Game can decide the match only when Stage One ends between 10-5 and 5-10: {decided} of "
              f"{len(finals)} matches ({decided / len(finals):.0%}). Outside that, Stage One clinched it.", "",
              "## Defaults set from this study", "",
              f"rating_center {center:.0f}, rating_points_per_logit {per_logit:.0f}, prior_rallies {final['prior_rallies']:.0f}, "
              f"season_decay {final['season_decay']}, doubles_weight {final['doubles_weight']}, team_rating_sd {best_sd} "
              "(config.toml keeps 0.05 by judgement: §3 is flat up to 0.05 and the hindsight ratings hide real uncertainty).", ""]
    (DIR / "RESEARCH.md").write_text("\n".join(lines))

    with (DIR / "data" / "backtest.csv").open("w", newline="") as fh:
        wr = csv.writer(fh)
        wr.writerow(["season", "date", "stage", "team_a", "team_b", "points_a", "points_b", "winner"])
        for m in finals:
            wr.writerow([m.season, m.date, m.stage, m.team_a, m.team_b, m.points_a, m.points_b, m.winner])
    print("\n".join(lines))


if __name__ == "__main__":
    main()
